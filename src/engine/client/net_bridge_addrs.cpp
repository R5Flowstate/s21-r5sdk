//-----------------------------------------------------------------------------
// Purpose: parses an IDA-style pattern ("48 8B ?? 24") into bytes and mask
//-----------------------------------------------------------------------------
static size_t NetObs_ParsePattern(const char* const pszPattern, uint8_t* const pBytes, char* const pMask, const size_t nMax)
{
	size_t n = 0;
	for (const char* p = pszPattern; *p && n < nMax; )
	{
		if (*p == ' ')
		{
			++p;
			continue;
		}
		if (*p == '?')
		{
			pBytes[n] = 0;
			pMask[n] = '?';
			++n;
			while (*p == '?')
				++p;
			continue;
		}
		if (!p[1])
			break;
		const char hex[3] = { p[0], p[1], 0 };
		pBytes[n] = static_cast<uint8_t>(strtoul(hex, nullptr, 16));
		pMask[n] = 'x';
		++n;
		p += 2;
	}
	pMask[n] = 0;
	return n;
}

static CMemory NetObs_FindPattern(const char* const pszPattern, const bool bReadOnlyData = false)
{
	if (!pszPattern)
		return CMemory();

	uint8_t bytes[512];
	char mask[513];
	const size_t n = NetObs_ParsePattern(pszPattern, bytes, mask, sizeof(bytes));
	if (!n)
		return CMemory();

	if (bReadOnlyData)
	{
		const CModule::ModuleSections_t rdata = g_GameDll.GetSectionByName(".rdata");
		return g_GameDll.FindPatternSIMD_Impl(bytes, mask, n, &rdata);
	}
	return g_GameDll.FindPatternSIMD_Impl(bytes, mask, n);
}

//-----------------------------------------------------------------------------
// Purpose: rejects any host image the symbol table was not verified against
//-----------------------------------------------------------------------------
bool NetObs_HostImageSupported(void)
{
	const IMAGE_NT_HEADERS64* const nt = g_GameDll.GetNTHeaders();
	if (!nt)
		return false;

	const uint32_t stamp = nt->FileHeader.TimeDateStamp;
	const uint32_t size = nt->OptionalHeader.SizeOfImage;
	for (size_t i = 0; i < SDK_ARRAYSIZE(s_NetObsHostImages); ++i)
	{
		const NetObsHostImage_t& img = s_NetObsHostImages[i];
		if (img.nTimeDateStamp == stamp && img.nSizeOfImage == size)
		{
			s_nNetObsHostIndex = static_cast<int>(i);
			return true;
		}
	}

	return false;
}

static uintptr_t NetObs_ResolveOne(const NetObsSymDesc_t& d)
{
	if (d.nKind == SYM_OFFSET)
	{
		const uintptr_t base = s_NetObsSymAddr[static_cast<size_t>(d.nBase)];
		return base ? base + d.nDelta : 0;
	}

	if (d.nKind == SYM_STRING)
		return NetObs_FindPattern(d.pszPattern, true).GetPtr();

	// A split entry carries one pattern per image: pszPattern for DX11,
	// pszPatternAlt for DX12. The gate picks; a pattern is never tried on
	// the image it was not verified against.
	const bool bUseAlt = d.pszPatternAlt && s_nNetObsHostIndex == 1;
	const CMemory m = NetObs_FindPattern(bUseAlt ? d.pszPatternAlt : d.pszPattern);
	const uint8_t ripOff = bUseAlt ? d.nRipOffAlt : d.nRipOff;
	const uint8_t insnLen = bUseAlt ? d.nInsnLenAlt : d.nInsnLen;
	if (!m)
		return 0;

	if (d.nKind == SYM_DATA)
		return m.ResolveRelativeAddress(ripOff, insnLen).GetPtr();
	return m.GetPtr();
}

//-----------------------------------------------------------------------------
// Purpose: resolves the whole table once; every entry is logged so a missing
// symbol shows at boot instead of at the first call
//-----------------------------------------------------------------------------
bool NetObs_ResolveSymbols(void)
{
	if (s_bNetObsSymsResolved)
		return s_bNetObsHostSupported && s_nNetObsSymsUnresolved == 0;
	s_bNetObsSymsResolved = true;

	if (!g_GameDll.GetModuleBase())
	{
		PEB64* const pEnv = CModule::GetProcessEnvironmentBlock();
		g_GameDll.InitFromBase(pEnv->ImageBaseAddress);
	}

	s_bNetObsHostSupported = NetObs_HostImageSupported() && s_nNetObsHostIndex >= 0;
	if (!s_bNetObsHostSupported)
	{
		const IMAGE_NT_HEADERS64* const nt = g_GameDll.GetNTHeaders();
		Warning(eDLL_T::CLIENT, "[NETOBS-SYM] unsupported host image (stamp=0x%08X size=0x%08X); symbols disabled\n",
			nt ? nt->FileHeader.TimeDateStamp : 0u, nt ? nt->OptionalHeader.SizeOfImage : 0u);
		return false;
	}

	const uint8_t hostBit = static_cast<uint8_t>(1u << s_nNetObsHostIndex);
	size_t nSkipped = 0;
	for (size_t i = 0; i < static_cast<size_t>(NetObsSym_t::COUNT); ++i)
	{
		const NetObsSymDesc_t& d = s_NetObsSymTable[i];
		if (!(d.nImageMask & hostBit))
		{
			s_NetObsSymAddr[i] = 0;
			++nSkipped;
			continue;
		}
		const uintptr_t addr = NetObs_ResolveOne(d);
		s_NetObsSymAddr[i] = addr;

		if (d.nKind == SYM_DATA)
			LogVarAdr(d.pszName, reinterpret_cast<void*>(addr));
		else
			LogFunAdr(d.pszName, reinterpret_cast<void*>(addr));

		if (!addr)
		{
			++s_nNetObsSymsUnresolved;
			Warning(eDLL_T::CLIENT, "[NETOBS-SYM] unresolved: %s\n", d.pszName);
		}
	}

	Msg(eDLL_T::CLIENT, "[NETOBS-SYM] %s: resolved %zu, unresolved %zu, other-image %zu of %zu symbols\n",
		s_NetObsHostImages[s_nNetObsHostIndex].pszLabel,
		static_cast<size_t>(NetObsSym_t::COUNT) - nSkipped - s_nNetObsSymsUnresolved,
		s_nNetObsSymsUnresolved, nSkipped, static_cast<size_t>(NetObsSym_t::COUNT));
	return s_nNetObsSymsUnresolved == 0;
}

size_t NetObs_UnresolvedCount(void)
{
	return s_nNetObsSymsUnresolved;
}

uintptr_t NetObs_SymResolved(const NetObsSym_t sym)
{
	if (!s_bNetObsSymsResolved)
		NetObs_ResolveSymbols();
	if (sym >= NetObsSym_t::COUNT)
		return 0;
	return s_NetObsSymAddr[static_cast<size_t>(sym)];
}

const char* NetObs_SymName(const NetObsSym_t sym)
{
	return sym < NetObsSym_t::COUNT ? s_NetObsSymTable[static_cast<size_t>(sym)].pszName : "?";
}
