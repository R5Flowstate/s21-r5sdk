//
// Purpose: Signature-resolved engine symbols for the client net bridge.
//
// Every engine address the bridge touches resolves once from a byte pattern
// against the host image. Data symbols resolve through the rip-relative
// operand of one referencing instruction. Offset symbols are interior code
// sites anchored on a resolved symbol in the same function.
//
//=============================================================================//
