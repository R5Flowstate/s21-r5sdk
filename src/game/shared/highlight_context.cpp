static SQRESULT Script_Entity_Highlight_SetCurrentContext(HSQUIRRELVM v)
{
	void* pEntity = nullptr;
	if (!v_sq_getentity(v, reinterpret_cast<SQEntity*>(&pEntity)))
		return SQ_ERROR;

	SQInteger contextId;
	sq_getinteger(v, 2, &contextId);

	if (!pEntity)
		SCRIPT_CHECK_AND_RETURN(v, SQ_OK);

	int id = static_cast<int>(contextId);

	if (IsVirtualContext(id))
	{
		int boundSlot = -1;
		if (EntityGenericHighlightState_t* state = s_entityGenericCtx.Find(pEntity))
		{
			for (int i = 0; i < 4; ++i)
			{
				if (state->ctxIdBySlot[i] == id)
				{
					boundSlot = i;
					break;
				}
			}
		}

		// Only bounce when the virtual ctxId transitions; repeated calls with
		// the same id would restart the fade animation every tick.
		int* prevVirtual = s_entityActiveVirtualContext.Find(pEntity);
		const bool virtualChanged = !prevVirtual || *prevVirtual != id;
		s_entityActiveVirtualContext[pEntity] = id;

		if (boundSlot >= 0)
		{
			if (virtualChanged)
				ForceClientEntitySetCurrentContext(pEntity, boundSlot);
			else
				v_ClientEnt_Highlight_SetCurrentContext(pEntity, boundSlot);
		}
		else
		{
			if (virtualChanged)
			{
				WriteContextToClientEntitySlot(pEntity, HIGHLIGHT_REMAP_PHYSICAL_SLOT, id);
				ForceClientEntitySetCurrentContext(pEntity, HIGHLIGHT_REMAP_PHYSICAL_SLOT);
			}
			else
			{
				v_ClientEnt_Highlight_SetCurrentContext(pEntity, HIGHLIGHT_REMAP_PHYSICAL_SLOT);
			}
		}
	}
	else
	{
		int* prevVirtual = s_entityActiveVirtualContext.Find(pEntity);
		const bool idChanged = !prevVirtual || *prevVirtual != id;
		if (id == -1)
			s_entityActiveVirtualContext.Erase(pEntity);
		else
			s_entityActiveVirtualContext[pEntity] = id;

		if (idChanged)
			ForceClientEntitySetCurrentContext(pEntity, id);
		else
			v_ClientEnt_Highlight_SetCurrentContext(pEntity, id);
	}

	SCRIPT_CHECK_AND_RETURN(v, SQ_OK);
}

// Returns the bound virtual ctxId (via s_entityGenericCtx or
// s_entityActiveVirtualContext) so script equality checks against their
// original HighlightContext_GetId result match.
static SQRESULT Script_Entity_Highlight_GetCurrentContext(HSQUIRRELVM v)
{
	void* pEntity = nullptr;
	if (!v_sq_getentity(v, reinterpret_cast<SQEntity*>(&pEntity)))
		return SQ_ERROR;

	int result = -1;
	if (pEntity)
	{
		uintptr_t ent = reinterpret_cast<uintptr_t>(pEntity);
		int physicalCtx = *reinterpret_cast<int*>(ent + CLIENT_ENT_HIGHLIGHT_CONTEXT_ID);

		if (physicalCtx == HIGHLIGHT_REMAP_PHYSICAL_SLOT)
		{
			int* pVirtualId = s_entityActiveVirtualContext.Find(pEntity);
			result = pVirtualId ? *pVirtualId : physicalCtx;
		}
		else if (physicalCtx >= 0 && physicalCtx < 4)
		{
			if (EntityGenericHighlightState_t* state = s_entityGenericCtx.Find(pEntity))
			{
				int bound = state->ctxIdBySlot[physicalCtx];
				result = (bound >= 0) ? bound : physicalCtx;
			}
			else
			{
				result = physicalCtx;
			}
		}
		else
		{
			result = physicalCtx;
		}
	}

	sq_pushinteger(v, result);
	SCRIPT_CHECK_AND_RETURN(v, SQ_OK);
}

static SQRESULT Script_Entity_Highlight_SetParam(HSQUIRRELVM v)
{
	void* pEntity = nullptr;
	if (!v_sq_getentity(v, reinterpret_cast<SQEntity*>(&pEntity)))
		return SQ_ERROR;

	SQInteger contextId, paramIdx;
	sq_getinteger(v, 2, &contextId);
	sq_getinteger(v, 3, &paramIdx);

	const SQVector3D* vec = nullptr;
	sq_getvector(v, 4, &vec);

	if (!pEntity || !vec || paramIdx < 0 || paramIdx > 1)
		SCRIPT_CHECK_AND_RETURN(v, SQ_OK);

	int id = static_cast<int>(contextId);

	if (IsVirtualContext(id))
	{
		if (IsValidContext(id))
		{
			s_contexts[id].params[paramIdx][0] = vec->x;
			s_contexts[id].params[paramIdx][1] = vec->y;
			s_contexts[id].params[paramIdx][2] = vec->z;
		}

		float vecData[3] = { vec->x, vec->y, vec->z };
		v_ClientEnt_Highlight_SetParam(pEntity, HIGHLIGHT_REMAP_PHYSICAL_SLOT,
			static_cast<int>(paramIdx), vecData);
	}
	else if (id >= 0 && id <= 7)
	{
		float vecData[3] = { vec->x, vec->y, vec->z };
		v_ClientEnt_Highlight_SetParam(pEntity, id,
			static_cast<int>(paramIdx), vecData);
	}

	SCRIPT_CHECK_AND_RETURN(v, SQ_OK);
}

//-----------------------------------------------------------------------------
// Binds a named context to generic-type slots 0..3 (physical slots 0..3).
//-----------------------------------------------------------------------------
static SQRESULT Script_Entity_Highlight_SetGenericHighlightContext(HSQUIRRELVM v)
{
	void* pEntity = nullptr;
	if (!v_sq_getentity(v, reinterpret_cast<SQEntity*>(&pEntity)))
		return SQ_ERROR;

	SQInteger genericType, contextId;
	SQBool isFocused;
	sq_getinteger(v, 2, &genericType);
	sq_getinteger(v, 3, &contextId);
	sq_getbool(v, 4, &isFocused);

	if (!pEntity)
		SCRIPT_CHECK_AND_RETURN(v, SQ_OK);

	int type = static_cast<int>(genericType);
	int ctxId = static_cast<int>(contextId);

	if (type < 0 || type > 7)
		SCRIPT_CHECK_AND_RETURN(v, SQ_OK);

	EntityGenericHighlightState_t& state = s_entityGenericCtx[pEntity];

	if (!IsValidContext(ctxId))
	{
		if (type < 4)
			state.ctxIdBySlot[type] = -1;
		if (v_ClientEnt_Highlight_SetFunctions)
		{
			v_ClientEnt_Highlight_SetFunctions(pEntity, type, 0, true, 0, 0.0f, 0, false);
			MarkClientEntityHighlightDirty(pEntity);
		}
		SCRIPT_CHECK_AND_RETURN(v, SQ_OK);
	}

	const HighlightContextData_t& ctx = s_contexts[ctxId];
	int insideFn  = isFocused && ctx.insideFunctionFocused  ? ctx.insideFunctionFocused  : ctx.insideFunction;
	int outsideFn = isFocused && ctx.outsideFunctionFocused ? ctx.outsideFunctionFocused : ctx.outsideFunction;

	if (type < 4)
		state.ctxIdBySlot[type] = ctxId;

	if (v_ClientEnt_Highlight_SetFunctions)
	{
		v_ClientEnt_Highlight_SetFunctions(
			pEntity, type,
			insideFn, ctx.isEntityVisible, outsideFn,
			ctx.outlineRadius, ctxId,
			ctx.isAfterPostProcess);
	}

	if (v_ClientEnt_Highlight_SetParam)
	{
		float p0[3] = { ctx.params[0][0], ctx.params[0][1], ctx.params[0][2] };
		float p1[3] = { ctx.params[1][0], ctx.params[1][1], ctx.params[1][2] };
		v_ClientEnt_Highlight_SetParam(pEntity, type, 0, p0);
		v_ClientEnt_Highlight_SetParam(pEntity, type, 1, p1);
	}

	MarkClientEntityHighlightDirty(pEntity);

	SCRIPT_CHECK_AND_RETURN(v, SQ_OK);
}

static SQRESULT Script_Entity_Highlight_GetGenericHighlightContext(HSQUIRRELVM v)
{
	void* pEntity = nullptr;
	if (!v_sq_getentity(v, reinterpret_cast<SQEntity*>(&pEntity)))
		return SQ_ERROR;

	SQInteger genericType;
	sq_getinteger(v, 2, &genericType);

	int result = -1;
	int type = static_cast<int>(genericType);
	if (pEntity && type >= 0 && type < 4)
	{
		EntityGenericHighlightState_t* state = s_entityGenericCtx.Find(pEntity);
		if (state)
			result = state->ctxIdBySlot[type];
	}

	sq_pushinteger(v, result);
	SCRIPT_CHECK_AND_RETURN(v, SQ_OK);
}

static SQRESULT Script_Entity_Highlight_OverrideParam(HSQUIRRELVM v)
{
	void* pEntity = nullptr;
	if (!v_sq_getentity(v, reinterpret_cast<SQEntity*>(&pEntity)))
		return SQ_ERROR;

	SQInteger paramIdx;
	sq_getinteger(v, 2, &paramIdx);

	const SQVector3D* vec = nullptr;
	sq_getvector(v, 3, &vec);

	if (!pEntity || !vec || paramIdx < 0 || paramIdx > 1)
		SCRIPT_CHECK_AND_RETURN(v, SQ_OK);

	int currentCtx = *reinterpret_cast<int*>(
		reinterpret_cast<uintptr_t>(pEntity) + CLIENT_ENT_HIGHLIGHT_CONTEXT_ID);

	if (currentCtx >= 0 && currentCtx <= 7 && v_ClientEnt_Highlight_SetParam)
	{
		float vecData[3] = { vec->x, vec->y, vec->z };
		v_ClientEnt_Highlight_SetParam(pEntity, currentCtx, static_cast<int>(paramIdx), vecData);
	}

	SCRIPT_CHECK_AND_RETURN(v, SQ_OK);
}

// Registers AddFunction entries under the same names as engine entity
// methods so scripts call our wrappers instead of the natives.
void HighlightContext_RegisterEntityOverrides(ScriptClassDescriptor_t* entityStruct)
{
	if (!v_ClientEnt_Highlight_SetCurrentContext)
	{
		Warning(eDLL_T::CLIENT, "[HighlightContext] Pattern scan failed for ClientEnt_Highlight_SetCurrentContext -- entity overrides disabled\n");
		return;
	}
	if (!v_ClientEnt_Highlight_SetParam)
	{
		Warning(eDLL_T::CLIENT, "[HighlightContext] Pattern scan failed for ClientEnt_Highlight_SetParam -- entity overrides disabled\n");
		return;
	}
	if (!v_ClientEnt_Highlight_SetFunctions)
	{
		// Non-fatal: other overrides still function.
		Warning(eDLL_T::CLIENT, "[HighlightContext] Pattern scan failed for ClientEnt_Highlight_SetFunctions -- generic-context override disabled\n");
	}

	entityStruct->AddFunction(
		"Highlight_SetCurrentContext",
		"Script_Entity_Highlight_SetCurrentContext",
		"Sets highlight context with virtual ID remapping (SDK)",
		"void",
		"int contextId",
		false,
		Script_Entity_Highlight_SetCurrentContext);

	entityStruct->AddFunction(
		"Highlight_GetCurrentContext",
		"Script_Entity_Highlight_GetCurrentContext",
		"Gets highlight context with virtual ID reverse mapping (SDK)",
		"int",
		"",
		false,
		Script_Entity_Highlight_GetCurrentContext);

	entityStruct->AddFunction(
		"Highlight_SetParam",
		"Script_Entity_Highlight_SetParam",
		"Sets highlight param with virtual ID remapping (SDK)",
		"void",
		"int contextId, int paramIdx, vector value",
		false,
		Script_Entity_Highlight_SetParam);

	entityStruct->AddFunction(
		"Highlight_SetGenericHighlightContext",
		"Script_Entity_Highlight_SetGenericHighlightContext",
		"Bind a named context to a generic-type slot",
		"void",
		"int genericType, int contextId, bool isFocused",
		false,
		Script_Entity_Highlight_SetGenericHighlightContext);

	entityStruct->AddFunction(
		"Highlight_GetGenericHighlightContext",
		"Script_Entity_Highlight_GetGenericHighlightContext",
		"Read back the ctxId bound to a generic-type slot (SDK)",
		"int",
		"int genericType",
		false,
		Script_Entity_Highlight_GetGenericHighlightContext);

	entityStruct->AddFunction(
		"Highlight_OverrideParam",
		"Script_Entity_Highlight_OverrideParam",
		"Override a param on the entity's current active slot (SDK)",
		"void",
		"int paramIdx, vector value",
		false,
		Script_Entity_Highlight_OverrideParam);
}

// Interception is via AddFunction overrides, no C++ detours needed.

void HighlightContext_LevelShutdown()
{
	for (int i = 0; i < MAX_HIGHLIGHT_CONTEXTS; i++)
		s_contexts[i] = HighlightContextData_t();

	s_nameToId.clear();
	s_nextId = 0;
	s_s21IdsReady = false;
	s_entityActiveVirtualContext.Clear();
	s_entityGenericCtx.Clear();
}
