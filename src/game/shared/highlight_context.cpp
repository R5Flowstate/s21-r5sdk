static const HighlightDefault_t* FindDefault(const char* name)
{
	for (size_t i = 0; i < kHighlightDefaultsCount; ++i)
	{
		if (strcmp(kHighlightDefaults[i].name, name) == 0)
			return &kHighlightDefaults[i];
	}
	return nullptr;
}

