static void ApplyHighlightDefault(HighlightContextData_t& ctx, const char* name)
{
	const HighlightDefault_t* def = FindDefault(name);
	if (!def)
		return;
	ctx.insideFunction          = def->insideSlot;
	ctx.insideFunctionFocused   = def->insideSlotFocused;
	ctx.outsideFunction         = def->outsideSlot;
	ctx.outsideFunctionFocused  = def->outsideSlotFocused;
	ctx.outlineRadius           = def->outlineRadius;
	ctx.drawFunc                = def->drawFunc;
	ctx.isEntityVisible         = def->entityVisible;
	ctx.isAfterPostProcess      = def->afterPostProcess;
	ctx.adsFade                 = def->adsFade;
	ctx.nearFadeDistance        = def->nearFadeDistance;
	ctx.farFadeDistance         = def->farFadeDistance;
	ctx.colorID                 = def->colorID;
	for (int k = 0; k < 3; ++k) ctx.params[0][k] = def->param0[k];
	for (int k = 0; k < 3; ++k) ctx.params[1][k] = def->param1[k];
}

static void EnsureS21HighlightIds(void)
{
	if (s_s21IdsReady)
		return;
	s_s21IdsReady = true;

	for (int id = 0; id < kS21HighlightIdCount; ++id)
	{
		const char* name = kS21HighlightIds[id];
		if (!name || !*name)
			continue;
		if (s_nameToId.find(name) != s_nameToId.end())
			continue;
		if (id >= MAX_HIGHLIGHT_CONTEXTS)
			break;

		HighlightContextData_t& ctx = s_contexts[id];
		strncpy(ctx.name, name, sizeof(ctx.name) - 1);
		ctx.registered = true;
		ApplyHighlightDefault(ctx, name);
		s_nameToId[name] = id;
	}

	if (s_nextId < kS21HighlightIdCount)
		s_nextId = kS21HighlightIdCount;

	Msg(eDLL_T::SERVER, "[HL-ID] baked %d S21 hcxt ids (id0='%s')\n",
		kS21HighlightIdCount, kS21HighlightIds[0]);
}

static int FindOrCreateContext(const char* name)
{
	if (!name || !*name)
		return INVALID_HIGHLIGHT_ID;

	EnsureS21HighlightIds();

	auto it = s_nameToId.find(name);
	if (it != s_nameToId.end())
		return it->second;

	if (s_nextId >= MAX_HIGHLIGHT_CONTEXTS)
		return INVALID_HIGHLIGHT_ID;

	int id = s_nextId++;
	HighlightContextData_t& ctx = s_contexts[id];
	strncpy(ctx.name, name, sizeof(ctx.name) - 1);
	ctx.registered = true;
	ApplyHighlightDefault(ctx, name);

	s_nameToId[name] = id;
	return id;
}

static bool IsValidContext(int id)
{
	return id >= 0 && id < MAX_HIGHLIGHT_CONTEXTS && s_contexts[id].registered;
}

static bool IsVirtualContext(int id)
{
	return id > 7 && id < MAX_HIGHLIGHT_CONTEXTS;
}

// Flip the highlight-dirty bit the client SetFunctions skips, and register
// into the slab at +0x2C38 or Highlight_SetVisibilityType silently no-ops.
static void MarkClientEntityHighlightDirty(void* entity)
{
	if (!g_pHighlightSystem || !*g_pHighlightSystem || !entity)
		return;

	const uintptr_t entAddr = reinterpret_cast<uintptr_t>(entity);
	const uint16_t handle = *reinterpret_cast<const uint16_t*>(entAddr + 88);
	if (handle == 0xFFFF)
		return;

	uint8_t* const systemBase = static_cast<uint8_t*>(*g_pHighlightSystem);
	uint8_t* const tableBase = *reinterpret_cast<uint8_t**>(systemBase + 120);
	if (!tableBase)
		return;

	volatile short* const slot = reinterpret_cast<volatile short*>(tableBase + 2 * handle + 64);
	_InterlockedOr16(slot, 0x200);

	// is idempotent via entity[+1857]==0 guard.
	if (v_ClientEnt_Highlight_RegisterWithSystem
	 && g_pHighlightEntitySlab)
	{
		const uint16_t slotIdx = *reinterpret_cast<const uint16_t*>(entAddr + 1858);
		if (slotIdx != 0xFFFF && slotIdx != 0xFFFD)
		{
			void* const slabEntPtr = *reinterpret_cast<void* const*>(
				g_pHighlightEntitySlab + 0x2C38 + 16 * slotIdx);
			const uint8_t registered = *reinterpret_cast<const uint8_t*>(entAddr + 1857);
			if (!slabEntPtr && registered == 0)
				v_ClientEnt_Highlight_RegisterWithSystem(entity, 0);
		}
	}
}

// SetCurrentContext early-outs when target==current. Bounce via -1 so
// funcBits that changed while the slot was already active get re-applied.
static void ForceClientEntitySetCurrentContext(void* entity, int targetSlot)
{
	const uintptr_t entAddr = reinterpret_cast<uintptr_t>(entity);
	const int currentCtx = *reinterpret_cast<int*>(entAddr + CLIENT_ENT_HIGHLIGHT_CONTEXT_ID);

	if (currentCtx == targetSlot)
		v_ClientEnt_Highlight_SetCurrentContext(entity, -1);

	v_ClientEnt_Highlight_SetCurrentContext(entity, targetSlot);
	MarkClientEntityHighlightDirty(entity);
}

// Apply named-context config to a physical slot via engine natives. Must
// route through SetFunctions/SetParam — raw packing mis-bits byte3
// (drawFunc vs highlightId) and the render shader reads the wrong config.
static void WriteContextToClientEntitySlot(void* entity, int physicalSlot, int virtualId)
{
	if (virtualId < 0 || virtualId >= MAX_HIGHLIGHT_CONTEXTS || !s_contexts[virtualId].registered)
		return;
	if (physicalSlot < 0 || physicalSlot > 7)
		return;

	const HighlightContextData_t& ctx = s_contexts[virtualId];

	if (v_ClientEnt_Highlight_SetFunctions)
	{
		v_ClientEnt_Highlight_SetFunctions(
			entity,
			physicalSlot,
			ctx.insideFunction,
			ctx.isEntityVisible,
			ctx.outsideFunction,
			ctx.outlineRadius,
			virtualId,
			ctx.isAfterPostProcess);
	}

	if (v_ClientEnt_Highlight_SetParam)
	{
		float p0[3] = { ctx.params[0][0], ctx.params[0][1], ctx.params[0][2] };
		float p1[3] = { ctx.params[1][0], ctx.params[1][1], ctx.params[1][2] };
		v_ClientEnt_Highlight_SetParam(entity, physicalSlot, 0, p0);
		v_ClientEnt_Highlight_SetParam(entity, physicalSlot, 1, p1);
	}

	MarkClientEntityHighlightDirty(entity);
}

SQRESULT Script_HighlightContext_GetId(HSQUIRRELVM v)
{
	const SQChar* name = nullptr;
	if (SQ_FAILED(sq_getstring(v, 2, &name)) || !name)
		return SQ_ERROR;

	int id = FindOrCreateContext(name);

	sq_pushinteger(v, id);
	SCRIPT_CHECK_AND_RETURN(v, SQ_OK);
}

SQRESULT Script_HighlightContext_SetParam(HSQUIRRELVM v)
{
	SQInteger contextId, paramIdx;
	sq_getinteger(v, 2, &contextId);
	sq_getinteger(v, 3, &paramIdx);

	const SQVector3D* vec = nullptr;
	sq_getvector(v, 4, &vec);

	if (IsValidContext(static_cast<int>(contextId)) && paramIdx >= 0 && paramIdx < MAX_HIGHLIGHT_PARAMS && vec)
	{
		s_contexts[contextId].params[paramIdx][0] = vec->x;
		s_contexts[contextId].params[paramIdx][1] = vec->y;
		s_contexts[contextId].params[paramIdx][2] = vec->z;
	}

	SCRIPT_CHECK_AND_RETURN(v, SQ_OK);
}

SQRESULT Script_HighlightContext_GetParam(HSQUIRRELVM v)
{
	SQInteger contextId, paramIdx;
	sq_getinteger(v, 2, &contextId);
	sq_getinteger(v, 3, &paramIdx);

	float x = 0.0f, y = 0.0f, z = 0.0f;
	if (IsValidContext(static_cast<int>(contextId)) && paramIdx >= 0 && paramIdx < MAX_HIGHLIGHT_PARAMS)
	{
		x = s_contexts[contextId].params[paramIdx][0];
		y = s_contexts[contextId].params[paramIdx][1];
		z = s_contexts[contextId].params[paramIdx][2];
	}

	SQVector3D result_vec(x, y, z);
	sq_pushvector(v, &result_vec);
	SCRIPT_CHECK_AND_RETURN(v, SQ_OK);
}

